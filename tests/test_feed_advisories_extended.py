@pytest.mark.parametrize('mode', ['duplicate', 'oversize', 'identity', 'escaped', 'too-many', 'missing', 'broken'])
def test_bad_jar_cannot_claim_fixed(tmp_path, mode):
    key = next(iter(MAVEN));name = MAVEN[key];path = tmp_path / 'jackson-databind.jar'
    good = 'groupId=com.fasterxml.jackson.core\nartifactId=jackson-databind\nversion=2.22.4\n'
    with warnings.catch_warnings():
        warnings.simplefilter('ignore', UserWarning)
        with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as z:
            if mode == 'duplicate':z.writestr(key, good);z.writestr(key, good.replace('2.22.4', '2.22.3'))
            elif mode == 'oversize':z.writestr(key, good + '#' * 17000)
            elif mode == 'identity':z.writestr(key, good.replace('jackson-databind', 'other'))
            elif mode == 'escaped':z.writestr(key, good.replace('2.22.4', '2.22.\\4'))
            elif mode == 'too-many':
                z.writestr(key, good)
                for n in range(MAX_JAR_ENTRIES):z.writestr(str(n), '')
            elif mode == 'broken':z.writestr(key, 'version=2.22.4')
    report = Scan().run([tmp_path]);assert report['incomplete'] and not report['records']


