def write_jar(path, identity, version, *, extra=()):
    group, artifact = identity.split(':')
    key = f'META-INF/maven/{group}/{artifact}/pom.properties'
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr(key, f'#Generated by Maven\ngroupId={group}\nartifactId={artifact}\nversion={version}\n')
        for name, data in extra: z.writestr(name, data)
    return path


def fixture(root, name, version, route):
    if route == 'maven':
        return write_jar(root / (name.split(':')[1] + '.jar'), name, version)
    if route == 'composer':
        path = root / 'vendor/composer/installed.json'
        data = json.dumps({'packages': [{'name': name, 'version': version}]}).encode()
    elif route == 'homebrew':
        path = root / 'Cellar' / name / 'installed/INSTALL_RECEIPT.json'
        data = json.dumps({'source': {'tap': 'homebrew/core', 'spec': 'stable', 'versions': {'stable': version}}}).encode()
    elif route == 'app':
        path = root / 'LM Studio.app/Contents/Info.plist'
        data = plistlib.dumps({'CFBundleIdentifier': 'ai.elementlabs.lmstudio', 'CFBundleShortVersionString': version})
    elif route == 'cask':
        path = root / 'Caskroom/clickhouse/.metadata/INSTALL_RECEIPT.json'
        data = json.dumps({'source': {'tap': 'homebrew/cask', 'version': version}}).encode()
    elif route == 'wordpress':
        path = root / 'wp-includes/version.php'
        data = f"<?php\n/** WordPress Version */\n$wp_version = '{version}';\n".encode()
    elif route == 'avada':
        path = root / 'wp-content/themes/Avada/style.css'
        data = f'/*\nTheme Name: Avada\nTheme URI: https://avada.com/\nVersion: {version}\n*/\nbody {{color:black}}'.encode()
    elif route == 'nextcloud':
        path = root / 'apps/richdocumentscode/appinfo/info.xml'
        data = f'<info><id>richdocumentscode</id><version>{version}</version></info>'.encode()
    else:
        path = root / 'embedded/service/gitlab-rails/VERSION'
        data = (version + '\n').encode()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return path


@pytest.mark.parametrize('name,route,old,fixed,states', CASES)
def test_real_discovery_and_fixed_update(tmp_path, name, route, old, fixed, states):
    path = fixture(tmp_path, name, old, route)
    report = Scan().run([tmp_path])
    assert not report['incomplete']
    assert len(report['records']) == 1
    before = report['records'][0]
    assert before['path'] == str(path) and before['name'] == name
    assert [r['state'] for r in before['advisories']] == states
    assert all(r['enforcement'] == 'finding_only' for r in before['advisories'])
    assert before['finding'] is None and before['running_state'] == 'unknown'
    fixture(tmp_path, name, fixed, route)
    after = Scan().run([tmp_path])['records'][0]
    assert after['id'] == before['id'] and after['metadata_sha256'] != before['metadata_sha256']
    assert all(r['state'] == 'fixed_for_advisory' for r in after['advisories'])
    assert after['configuration'] == after['running_state'] == 'unknown'


