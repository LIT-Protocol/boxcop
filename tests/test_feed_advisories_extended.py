    payload = cask_root / 'clickhouse/26.10.2.103-stable'
    payload.mkdir()
    (payload / 'package.json').write_text('not metadata')
    report = Scan().run()
    assert not report['incomplete']
    assert {'next', 'clickhouse'} <= {row['name'] for row in report['records']}
    assert all(row['advisories'] for row in report['records'] if row['name'] in {'next', 'clickhouse'})
