def test_automatic_layouts_reach_feed_packages_and_cask_receipts(tmp_path, monkeypatch):
    from server import software_inventory
    roots = [tmp_path / str(i) / root.name for i, root in enumerate(defaults(tmp_path / 'home'))]
    monkeypatch.setattr(software_inventory, 'defaults', lambda: roots)
    node_root = next(root for root in roots if root.name == 'node')
    package = node_root / 'v22.0.0/lib/node_modules/next'
    package.mkdir(parents=True)
    (package / 'package.json').write_text(json.dumps({'name': 'next', 'version': '15.0.0'}))
    cask_root = next(root for root in roots if root.name == 'Caskroom')
    receipt = cask_root / 'clickhouse/.metadata/INSTALL_RECEIPT.json'
